        stroke: "rgba(0,0,0,0.1)",
        strokeMiterLimit: "10",
        strokeDasharray: "5 10",
        strokeDashOffset: "180"
    });

    // SVG C - Triangle (As Polyline)
    var Triangle = snapC.polyline("0, 30, 15, 0, 30, 30");
    Triangle.attr({
        id: "plane",
        fill: "rgba(0,0,0,0.050)"
    });

    initTriangle();

    // Initialize Triangle on Path
    function initTriangle() {
        var triangleGroup = snapC.g(Triangle); // Group polyline 
        movePoint = myPathC.getPointAtLength(length);
        triangleGroup.transform('t' + parseInt(movePoint.x - 15) + ',' + parseInt(movePoint.y - 15) + 'r' + (
            movePoint.alpha - 90));
    }

    // SVG C - Draw Path
    var lenC = myPathC.getTotalLength();

    // SVG C - Animate Path
    function animateSVG() {

        myPathC.attr({
            stroke: 'rgba(0,0,0,0.1)',
            strokeWidth: 1,
            fill: 'none',
            // Draw Path
            "stroke-dasharray": "5 10",
            "stroke-dashoffset": "180"
        }).animate({
            "stroke-dashoffset": 10
        }, 2500, mina.easeinout);

        var triangleGroup = snapC.g(Triangle); // Group polyline

        setTimeout(function() {
            Snap.animate(0, lenC, function(value) {

                movePoint = myPathC.getPointAtLength(value);

                triangleGroup.transform('t' + parseInt(movePoint.x - 15) + ',' + parseInt(
                    movePoint.y - 15) + 'r' + (movePoint.alpha - 90));

            }, 2500, mina.easeinout, function() {});
        });

    }


    // Animate Button
    function kapow() {
        $(window).on('scroll', function() {
            // Run SVG
            animateSVG();
        });
    }

    kapow();

});
